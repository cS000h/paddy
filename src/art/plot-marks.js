// 地里的毛病画在土上：长了杂草、叶子上有虫。16×16、透明底，盖在土和作物上面，
// 画在格子的边角，留出正中给作物，一眼就能看出这格地要照料。
import { fromText } from './pixel.js';
import { P } from './palette.js';

const WEEDS = [
  '................',
  '.G..............',
  '.gG.G...........',
  'GgGgg.......G...',
  '.ggg.......GgG..',
  '...........ggg..',
  '................',
  '................',
  '................',
  '................',
  '..............G.',
  '.G.G.........GgG',
  '.GgG..........g.',
  'GgGgG...........',
  '.ggg............',
  '................',
];

const BUGS = [
  '................',
  '................',
  '..........k.....',
  '.........kRk....',
  '..........k.....',
  '................',
  '..k.............',
  '.kRk............',
  '..k.............',
  '................',
  '................',
  '.........k......',
  '........kRk.....',
  '.........k......',
  '................',
  '................',
];

const MARKS = {
  weeds: () => fromText(WEEDS, { G: P.g4, g: P.g6 }),
  bugs: () => fromText(BUGS, { k: P.ink1, R: P.c2 }),
};

/** 地里毛病的名字：weeds、bugs。 */
export const PLOT_MARKS = Object.keys(MARKS);

/** 某种毛病的小图。 */
export function plotMark(name) {
  const make = MARKS[name];
  if (!make) throw new Error('没有这种地里的毛病：' + name);
  return make();
}
