// 不动存档里随机数的「固定的随机」：钓鱼锄出蚯蚓、每天清早哪几处有动静，都只看日子、种子、地点这几个整数。
// 清早挑东西要是用存档里的随机数，后面每一次抽签都跟着变，别处的收成就全不一样了。
/** 一个 0 到 1 的数，只看传进来的几个整数（同样的数给同样的结果），不动存档里的随机数。 */
export function noise(...ns) {
  let h = 2166136261;
  for (const n of ns) {
    h ^= n >>> 0;
    h = Math.imul(h, 16777619) >>> 0;
  }
  h ^= h >>> 13;
  h = Math.imul(h, 2246822507) >>> 0;
  h ^= h >>> 16;
  // 上面的 ^= 出来是有符号的 32 位整数，一半是负数；先 >>> 0 转回无符号，才落在 0 到 1 之间
  return (h >>> 0) / 4294967296;
}
